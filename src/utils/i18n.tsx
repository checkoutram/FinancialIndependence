// Tamil / English i18n — tiny dictionary store with a React hook.
import { useSyncExternalStore } from 'react';

export type Lang = 'en' | 'ta';

const KEY = 'fire_lang';
let lang: Lang = ((): Lang => {
  try { return (localStorage.getItem(KEY) as Lang) === 'ta' ? 'ta' : 'en'; } catch { return 'en'; }
})();
const listeners = new Set<() => void>();

export function getLang(): Lang { return lang; }
export function setLang(l: Lang) {
  lang = l;
  try { localStorage.setItem(KEY, l); } catch { /* ignore */ }
  listeners.forEach(f => f());
}

function subscribe(f: () => void): () => void {
  listeners.add(f);
  return () => { listeners.delete(f); };
}

/** Hook — re-renders the component when the language changes. */
export function useLang(): Lang {
  return useSyncExternalStore(subscribe, () => lang);
}

export type Vars = Record<string, string | number>;
export type TFunc = (key: string, vars?: Vars) => string;

/** Translate with {placeholder} interpolation. Falls back to English, then the key itself. */
export function t(key: string, vars?: Vars): string {
  let s: string = DICT[lang][key] ?? DICT.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** Hook version of t — subscribes to language changes. */
export function useT(): TFunc {
  useLang();
  return t;
}

/** Compact EN / தமிழ் toggle for headers. */
export function LangToggle({ className = '' }: { className?: string }) {
  const l = useLang();
  return (
    <div className={`flex rounded-lg overflow-hidden border ${className}`} style={{ borderColor: 'var(--card-border)' }}>
      {(['en', 'ta'] as const).map(x => (
        <button key={x} type="button" onClick={() => setLang(x)}
          className="px-2.5 py-1.5 text-xs font-bold transition-colors"
          style={{ background: l === x ? 'var(--accent)' : 'transparent', color: l === x ? '#fff' : 'var(--text-dim)' }}>
          {x === 'en' ? 'EN' : 'தமிழ்'}
        </button>
      ))}
    </div>
  );
}

