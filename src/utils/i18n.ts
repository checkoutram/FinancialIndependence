const translations: Record<Language, Record<string, string>> = {
  en,
  ta: en,
  ml: en,
  te: en,
  kn: en,
  hi: en,
  mr: en,
};

let currentLanguage: Language = 'en';

export function setLanguage(lang: Language) {
  currentLanguage = lang;
  localStorage.setItem('finplan_language', lang);
}

export function getLanguage(): Language {
  const saved = localStorage.getItem('finplan_language') as Language;
  if (saved && LANGUAGES.find(l => l.code === saved)) {
    currentLanguage = saved;
  }
  return currentLanguage;
}

export function t(key: string, params?: Record<string, string | number>): string {
  const lang = getLanguage();
  let text = translations[lang]?.[key] || translations['en'][key] || key;

  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, String(v));
    });
  }

  return text;
}

export function formatDate(date: Date | string, lang?: Language): string {
  const d = typeof date === 'string' ? new Date(date) : date;
  return d.toLocaleDateString(lang === 'en' ? 'en-IN' : 'en-IN', {
    day: '2-digit',
    month: 'short',
    year: 'numeric'
  });
}
